// Topic 1: For loop
//Print numbers from 1 to 10
#include <stdio.h>
int main() {
    int i;
  for (i = 1; i <= 10; i++) {
        printf("%d\n", i);
  }
 return 0;
}

// Topic 2: While loop
// Print numbers from 1 to 10
#include <stdio.h>
int main() {
    int i = 1;
 while (i <= 10) {
        printf("%d\n", i);
        i++;
    }
 return 0;
}

// Topic 3: do-while loop
// Print numbers from 1 to 10
#include <stdio.h>
int main() {
    int i = 1;
  do {
       printf("%d\n", i);
        i++;
    } while (i <= 10);
return 0;
}

